"""Build a portable, private-by-use card preparation package; never image a disk."""
from pathlib import Path
import hashlib,json,os,subprocess,tarfile,tempfile,zipfile

ROOT=Path(__file__).resolve().parents[1]
STATE=Path('/var/lib/dataark/card-package')
PRIVATE=Path('/etc/dataark/appliance-jobs')

def portable_welcome(source_archive,folder):
    """Render the same template from the kit's committed source, not host files."""
    names=['app/services/welcome_guides.py','config/distribution-channels.json','app/static/assets/pharos-data-ark-clean.png','app/static/assets/dej-software-footer.webp']
    root=folder/'welcome-source'
    with tarfile.open(source_archive) as archive:
        for name in names:
            member=archive.getmember(name)
            if not member.isfile():raise ValueError('Welcome source must be a regular file')
            target=root/name;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(archive.extractfile(member).read())
    module=root/'app/services/welcome_guides.py';namespace={'__file__':str(module)}
    exec(compile(module.read_bytes(),str(module),'exec'),namespace)
    text=namespace['render']('microsd',code='0000',hostname='DATAARK_HOSTNAME',note='Sender: finish the initial online build and wait for its successful automatic power-off before handing over this card. Its chosen library capacity is {{LIBRARY_GIB}} GiB; capacity does not imply it is full.')
    marker='<div class="code">0000</div>'
    if marker not in text:raise ValueError('Welcome code field missing')
    return text.replace(marker,'<div class="code">{{SETUP_CODE}}</div>',1)

def status(phase,**fields):
    from tools.clone_drive import save
    save(STATE/'status.json',{'phase':phase,**fields})

def validate(library_gib,country):
    import re
    if type(library_gib) is not int or not 2<=library_gib<=1024 or not isinstance(country,str) or not re.fullmatch('[A-Z]{2}',country):raise ValueError('Choose 2–1024 GiB and a two-letter Wi-Fi country')

def build(library_gib,country,output):
    validate(library_gib,country)
    from tools.replicate_drive import kit_files
    from tools import content_profile
    profile=ROOT/'config/content/content.yaml'
    with tempfile.TemporaryDirectory(prefix='dataark-card-package-') as temp:
        folder=Path(temp);kit=folder/'kit';kit.mkdir();metadata=kit_files(kit,profile=profile,platform_profile="raspberry-pi-debian13-arm64")
        revision=metadata['source_revision']
        welcome=portable_welcome(kit/'DATA-ARK-RECOVERY/dataark-source.tar.gz',folder)
        def committed(name):return subprocess.check_output(['git','-c','safe.directory='+str(ROOT),'-C',str(ROOT),'show',revision+':'+name])
        payload=folder/'kit.tar.gz'
        with tarfile.open(payload,'w:gz') as archive:
            for path in sorted(kit.rglob('*')):
                if path.is_symlink():raise ValueError('Unexpected kit symlink')
                if path.is_file():archive.add(path,arcname=path.relative_to(kit).as_posix(),recursive=False)
        config={'schema':1,'library_gib':library_gib,'country':country,'kit_sha256':hashlib.sha256(payload.read_bytes()).hexdigest(),
                'image':json.loads(committed('config/ready-card-image.json')),'source_revision':revision,'first_boot_internet_required':True,'ready_card_starts_offline':True}
        readme='''PREPARE A READY-TO-RUN DATA ARK CARD

1. Extract this entire ZIP on Windows or Linux. The OS image is not included.
   Obtain the exact Raspberry Pi OS image named in card-package.json from the
   official Raspberry Pi archive. Install Raspberry Pi Imager 2.0.12 or newer.
2. On Windows, run prepare-card.cmd from an Administrator terminal.
   On Linux/Pi, run sudo python3 prepare-card.py. Select the image and destination.
   Review the disk/serial/size. Type its exact ERASE confirmation; all selected
   card contents will be replaced. System and live-library disks are refused.
3. Keep the PRIVATE welcome sheet generated by the writer. Every written card
   gets a fresh hostname and pairing code. No provisioner SSH key is installed.
4. Insert the card into a compatible Pi, connect Ethernet with internet and power.
   It builds the Ark automatically with the selected system-card library and fixed
   sample content. This initial build needs internet for software dependencies.
   It starts no large optional collection restoration. Progress is on the display
   and on the card in dataark-card/result.json; logs stay on the system card.
5. A successful build prepares recipient setup and POWERS OFF. Only then is the
   card ready to give away. An imaging success alone is not a finished offline Ark.
   The recipient's next boot needs no internet to read installed content or enroll.
   Give them the private sheet; their passwords and machine identity are new.

If building fails, keep the card and logs. Reboot retries the journaled build.
Never confuse this preparation ZIP with a bootable OS image or a full library.
The original Ark and its library are not changed by building this package.
'''
        output=Path(output);output.parent.mkdir(parents=True,exist_ok=True);part=output.with_suffix('.partial')
        with zipfile.ZipFile(part,'w',zipfile.ZIP_DEFLATED) as z:
            z.write(payload,'kit.tar.gz');z.writestr('card-package.json',json.dumps(config,indent=2)+'\n');z.writestr('README.txt',readme)
            z.writestr('welcome-template.html',welcome)
            for source,name in [('tools/ready_card_first_boot.py','first-boot.py'),('tools/ready_card_writer.py','prepare-card.py'),('deploy/prepare-card.ps1','prepare-card.ps1')]:z.writestr(name,committed(source))
            z.writestr('prepare-card.cmd','@echo off\r\npowershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0prepare-card.ps1" %*\r\n')
        part.replace(output)
        return {'bytes':output.stat().st_size,'sha256':hashlib.sha256(output.read_bytes()).hexdigest(),'source_revision':revision,'message':'Preparation package ready. Imaging and the first online build must finish before the card is ready to hand over.'}

def worker():
    job=json.loads((PRIVATE/'card-job.json').read_text());status('building',message='Packaging public software/configuration and the card writer. No physical card is being written.')
    try:
        result=build(job['library_gib'],job['country'],STATE/'data-ark-card-preparation.zip');status('ready',**result)
        from tools.appliance_jobs import emit
        emit('installed','card')
    except Exception as e:
        status('failed',message=str(e))
        from tools.appliance_jobs import emit
        emit('failed','card');raise
