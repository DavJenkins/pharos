#!/usr/bin/env python3
"""Publish portable orientation files without moving or rewriting library content."""
import argparse
from datetime import datetime, timezone
import hashlib
import html
import json
import os
from pathlib import Path
import tempfile
from urllib.parse import quote

MARKER = 'Generated by Data Ark content publisher v1'
OUTPUTS = {'BROWSE.html', 'START-HERE.html', 'README-DATA-ARK.txt', 'DATA-ARK-CATALOG.json'}
EXCLUDED = {'bugout-drop', 'System Volume Information', '$RECYCLE.BIN'}

def collect(root, checksums=False):
    entries = []
    device = root.stat().st_dev
    for directory, dirs, files in os.walk(root, followlinks=False, onerror=lambda e: (_ for _ in ()).throw(e)):
        keep = []
        for name in sorted(dirs):
            path = Path(directory) / name
            if not name.startswith('.') and name not in EXCLUDED and not path.is_symlink() and path.stat().st_dev == device:
                keep.append(name)
        dirs[:] = keep
        for name in sorted(files):
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if relative in OUTPUTS or name.startswith('.') or path.is_symlink():
                continue
            before = path.stat()
            entry = {'path': relative, 'bytes': before.st_size, 'modified_ns': before.st_mtime_ns}
            if checksums:
                with path.open('rb') as stream:
                    entry['sha256'] = hashlib.file_digest(stream, 'sha256').hexdigest()
                after = path.stat()
                if (after.st_size, after.st_mtime_ns) != (before.st_size, before.st_mtime_ns):
                    raise RuntimeError(f'File changed while hashing: {relative}')
            entries.append(entry)
    return entries

