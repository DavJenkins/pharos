def render_browse(entries):
    links = []
    for entry in entries:
        link = quote(entry['path'], safe='/')
        label = html.escape(entry['path'])
        links.append(f'<li><a href="{link}">{label}</a> ({entry["bytes"]:,} bytes)</li>')
    listing = '<ul>' + ''.join(links) + '</ul>' if links else '<p>No files cataloged yet.</p>'
    return ('<!doctype html><!-- ' + MARKER + ' --><html lang="en"><head>'
            '<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            '<title>Data Ark - All Files</title><style>body{font:17px/1.6 system-ui,sans-serif;max-width:1000px;margin:2rem auto;padding:0 1rem}li{overflow-wrap:anywhere}a{color:#075d89}</style>'
            '</head><body><a href="START-HERE.html">Start here</a><h1>All library files</h1>'
            '<p>Original files, including reader support files. Staging uploads and system metadata are excluded. Open ZIM archives in Kiwix.</p>' + listing + '</body></html>')

def publish(root, checksums=False):
    root = root.resolve()
    # Preflight all destinations before replacing any generated file.
    for name in OUTPUTS:
        path = root / name
        if path.is_symlink() or (path.exists() and MARKER not in path.read_text(encoding='utf-8')):
            raise RuntimeError(f'Refusing to overwrite a file not generated by this tool: {name}')
    entries = collect(root, checksums)
    generated = datetime.now(timezone.utc).isoformat(timespec='seconds')
    body, readme = render(entries, generated, checksums)
    catalog = {'generator': MARKER, 'generated': generated, 'checksums': checksums, 'excluded_directories': sorted(EXCLUDED), 'files': entries}
    payloads = {'BROWSE.html': render_browse(entries), 'START-HERE.html': body, 'README-DATA-ARK.txt': readme, 'DATA-ARK-CATALOG.json': json.dumps(catalog, indent=2, ensure_ascii=False)}
    for name, content in payloads.items():
        with tempfile.NamedTemporaryFile(dir=root, prefix='.dataark-', delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content.encode('utf-8'))
        try:
            # These are public distribution files; mkstemp defaults to 0600 on ext4.
            temp.chmod(0o644)
            os.replace(temp, root / name)
        finally:
            temp.unlink(missing_ok=True)
    return len(entries)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checksums', action='store_true', help='Read every content file to generate SHA-256 hashes; may take a long time.')
    args = parser.parse_args()
    root = Path('/mnt/storage')
    if not root.is_mount():
        raise SystemExit('SSD is not mounted at /mnt/storage; refusing to publish into the root filesystem.')
    print(f'Published portable catalog for {publish(root, args.checksums)} files.')
    print('Archive payloads were not moved or rewritten.')

if __name__ == '__main__':
    main()
